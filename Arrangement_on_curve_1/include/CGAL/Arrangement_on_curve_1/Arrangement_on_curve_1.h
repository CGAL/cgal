/*! \class Arrangement_on_curve_1
 * \tparam GeometryTraits_1
 *
 * \tparam TopologyTraits
 *
 * \tparam BinarySearch when true (requires UseVector = `true`), the locate()
 *                      function in locate.h uses a binary search over the sorted
 *                      vertex vector, reducing locate from \f$O(n)\f$ to \f$O(log n)\f$.
 *                      Not supported for an identified parameter space.
 */
template <typename GeometryTraits_1,
          typename TopologyTraits = typename Default_topology_traits<GeometryTraits_1>::type,
          bool BinarySearch = false>
class Arrangement_on_curve_1 {
  static_assert(! BinarySearch || TopologyTraits::use_vector,
    "BinarySearch = true requires TopologyTraits::UseVector = true: binary search is only "
    "available over a random-access container.");

public:
  using Geometry_traits_1 = GeometryTraits_1;
  using Topology_traits = TopologyTraits;
  static constexpr bool binary_search_enabled = BinarySearch;

  // The boundary-category tags come from the geometry traits.
  using Left_side_category = typename Geometry_traits_1::Left_side_category;
  using Right_side_category = typename Geometry_traits_1::Right_side_category;

  // True when both sides of the parameter space are identified.
  static constexpr bool is_identified =
    Side_is_identified<Left_side_category>::value && Side_is_identified<Right_side_category>::value;

  static_assert(! BinarySearch || ! is_identified,
    "BinarySearch = true is not supported for an identified parameter space: the vertices are cyclically "
    "ordered, and Compare_x_1 must not be called on the identification point.");

  // True when the left/right side is closed.
  static constexpr bool left_is_closed = Side_is_closed<Left_side_category>::value;
  static constexpr bool right_is_closed = Side_is_closed<Right_side_category>::value;

  // Define a clean type alias for the traits smart pointer
  using Shared_geometry_traits = std::shared_ptr<const Geometry_traits_1>;

  // Expose the allocator type from the topology traits so that callers can
  // query it via get_allocator() and use it with compatible containers.
  using Allocator = typename Topology_traits::Allocator;

  //! The standard stl type.
  using allocator_type = Allocator;

  using Point_1 = typename Geometry_traits_1::Point_1;

  using Vertex_descriptor = typename Topology_traits::Vertex_descriptor;
  using Edge_descriptor = typename Topology_traits::Edge_descriptor;

  using Vertex_const_descriptor = typename Topology_traits::Vertex_const_descriptor;
  using Edge_const_descriptor = typename Topology_traits::Edge_const_descriptor;

  using Size = typename Topology_traits::Size;

  // Location result: a point is either ON a vertex or INSIDE an edge
  using Location_result = std::variant<Vertex_descriptor, Edge_descriptor>;
  using Const_location_result = std::variant<Vertex_const_descriptor, Edge_const_descriptor>;

private:
  Shared_geometry_traits m_geometry_traits;
  Topology_traits m_topology_traits;

public:
  // ==========================================================================
  // Special member functions.
  //
  // The destructor, move constructor, and move assignment are all correct as
  // generated by the compiler: shared_ptr and TopologyTraits both have correct
  // move semantics (std::list moves without invalidating iterators).
  //
  // The copy constructor and copy assignment must be explicitly defaulted here
  // (rather than left fully implicit) so that their correctness is visible and
  // intentional: they delegate entirely to TopologyTraits's copy operations,
  // which perform the non-trivial cross-reference patching needed to produce a
  // fully independent copy with valid internal iterators.
  // ==========================================================================
  ~Arrangement_on_curve_1() = default;

  Arrangement_on_curve_1(const Arrangement_on_curve_1&) = default;
  Arrangement_on_curve_1& operator=(const Arrangement_on_curve_1&) = default;

  Arrangement_on_curve_1(Arrangement_on_curve_1&&) noexcept = default;
  Arrangement_on_curve_1& operator=(Arrangement_on_curve_1&&) noexcept = default;

  // 1. Default constructor: allocates a default-constructed traits instance on the heap
  Arrangement_on_curve_1() :
    m_geometry_traits(std::make_shared<const Geometry_traits_1>()),
    m_topology_traits()
  {}

  // 2. Constructor passing an existing smart pointer
  Arrangement_on_curve_1(Shared_geometry_traits shared_geom_tr) :
    m_geometry_traits(std::move(shared_geom_tr)),
    m_topology_traits()
  { CGAL_assertion(m_geometry_traits != nullptr); }

  // 3. Fully custom constructor with topology traits
  Arrangement_on_curve_1(Shared_geometry_traits shared_geom_tr, Topology_traits topo_tr) :
    m_geometry_traits(std::move(shared_geom_tr)),
    m_topology_traits(std::move(topo_tr))
  { CGAL_assertion(m_geometry_traits != nullptr); }

  // 4. Allocator-aware constructor.
  // Constructs an empty arrangement whose internal topology traits (and
  // therefore its vertex/edge lists) use the supplied allocator.
  // Requires that TopologyTraits is constructible from an Allocator.
  Arrangement_on_curve_1(Shared_geometry_traits shared_geom_tr, const Allocator& alloc) :
    m_geometry_traits(std::move(shared_geom_tr)),
    m_topology_traits(alloc)
  { CGAL_assertion(m_geometry_traits != nullptr); }

private:
  // asserts that `p` lies to the right of all the vertices when BinarySearch
  // is active, as vertices must be created in left-to-right order.
  void assert_rightmost(const Point_1& p) const {
    if constexpr (binary_search_enabled) {
      CGAL_assertion_msg(empty() ||
                         m_geometry_traits->compare_x_1_object()
                         (m_topology_traits.vertex_point(m_topology_traits.number_of_vertices() - 1), p) == SMALLER,
                         "When BinarySearch = true, vertices must be created in strictly increasing x-order.");
    }
    else CGAL_USE(p);
  }

  // creates a new vertex associated with `p` without determining whether `p`
  // lies on a boundary or is the identification point; the caller, which
  // knows, registers the vertex accordingly.
  Vertex_descriptor create_vertex_at(const Point_1& p) {
    assert_rightmost(p);
    return m_topology_traits.create_vertex(p);
  }

  // determines whether `p` lies in the interior of the parameter space, that
  // is, neither on a closed boundary nor at the identification point.
  bool is_interior(const Point_1& p) const {
    if constexpr (is_identified) return ! m_geometry_traits->is_on_x_identification_1_object()(p);
    else if constexpr (left_is_closed || right_is_closed)
      return m_geometry_traits->parameter_space_in_x_1_object()(p) == Parameter_space::INTERIOR;
    else {
      CGAL_USE(p);
      return true;
    }
  }

public:
  // ==========================================================================
  // MODIFIERS
  // ==========================================================================

  /*! creates a new vertex, enforcing the rightmost ordering invariant when BinarySearch is active,
   * and registers it as the left or right boundary vertex when the point lies on a closed boundary,
   * or as the identification vertex when the point is the identification point.
   */
  Vertex_descriptor create_vertex(const Point_1& p) {
    assert_rightmost(p);
    return m_topology_traits.create_vertex(p, *m_geometry_traits);
  }

  /*! creates an new edge.
   */
  Edge_descriptor create_edge() { return m_topology_traits.create_edge(); }

  /*! destroys a given vertex.
   */
  void destroy_vertex(Vertex_descriptor v) {
    if constexpr (binary_search_enabled) {
      // Enforce that only the rightmost vertex can be destroyed in \f$O(1)\f$ time
      // without invalidating stored vertex indices in existing edges.
      CGAL_assertion_msg(v == this->topology_traits().number_of_vertices() - 1,
                         "When BinarySearch = true, only the rightmost vertex can be destroyed.");
    }

    this->topology_traits().erase_vertex(v);
  }

  /*! destroys a given edge.
   */
  void destroy_edge(Edge_descriptor e) { this->topology_traits().erase_edge(e); }

  /*! clears
   */
  void clear() { m_topology_traits.clear(); }

  void reset_shared_geometry_traits(Shared_geometry_traits new_shared_geom_tr) {
    // Safety check: changing traits on a populated structure is highly dangerous
    CGAL_precondition_msg(empty(), "Cannot reset the geometry traits pointer of a non-empty arrangement.");
    CGAL_assertion(new_shared_geom_tr != nullptr);
    m_geometry_traits = new_shared_geom_tr;
  }

  // ==========================================================================
  // ACCESSORS
  // ==========================================================================

  const Geometry_traits_1& geometry_traits_1() const { return *m_geometry_traits; }
  Shared_geometry_traits shared_geometry_traits_1() const { return m_geometry_traits; }

  const Topology_traits& topology_traits() const { return m_topology_traits; }
  Topology_traits& topology_traits() { return m_topology_traits; }

  bool empty() const { return m_topology_traits.empty(); }
  Size number_of_vertices() const { return m_topology_traits.number_of_vertices(); }
  Size number_of_edges() const { return m_topology_traits.number_of_edges(); }

  auto vertices() const { return m_topology_traits.vertices(); }
  auto edges() const { return m_topology_traits.edges(); }

  auto vertex_point_map() const { return m_topology_traits.vertex_point_map(); }
  auto vertex_data_map() const { return m_topology_traits.vertex_data_map(); }
  auto edge_data_map() const { return m_topology_traits.edge_data_map(); }

  Edge_descriptor left_boundary_edge() { return m_topology_traits.left_boundary_edge(); }
  Edge_const_descriptor left_boundary_edge() const { return m_topology_traits.left_boundary_edge(); }

  Edge_descriptor right_boundary_edge() { return m_topology_traits.right_boundary_edge(); }
  Edge_const_descriptor right_boundary_edge() const { return m_topology_traits.right_boundary_edge(); }

  Vertex_descriptor left_vertex(Edge_descriptor e) { return m_topology_traits.left_vertex(e); }
  Vertex_descriptor right_vertex(Edge_descriptor e) { return m_topology_traits.right_vertex(e); }
  Edge_descriptor left_edge(Vertex_descriptor v) { return m_topology_traits.left_edge(v); }
  Edge_descriptor right_edge(Vertex_descriptor v) { return m_topology_traits.right_edge(v); }

  Vertex_const_descriptor left_vertex(Edge_const_descriptor e) const { return m_topology_traits.left_vertex(e); }
  Vertex_const_descriptor right_vertex(Edge_const_descriptor e) const { return m_topology_traits.right_vertex(e); }
  Edge_const_descriptor left_edge(Vertex_const_descriptor v) const{ return m_topology_traits.left_edge(v); }
  Edge_const_descriptor right_edge(Vertex_const_descriptor v) const { return m_topology_traits.right_edge(v); }

  bool has_left_vertex(Edge_const_descriptor e) const { return m_topology_traits.has_left_vertex(e); }
  bool has_right_vertex(Edge_const_descriptor e) const { return m_topology_traits.has_right_vertex(e); }

  // obtains the allocator used by the internal topology traits.
  Allocator get_allocator() const noexcept { return m_topology_traits.get_allocator(); }

  // ============================================================================
  // HIGH-LEVEL TOPOLOGICAL OPERATIONS
  // ============================================================================

  /* inserts the very first point into an empty arrangement.
   *
   * For open/closed topologies the single edge is split into two.
   * For identified topologies the single edge becomes a self-loop at the new vertex
   */
  Vertex_descriptor insert_empty(const Point_1& p) {
    auto& topo = m_topology_traits;

    auto e_left_boundary = topo.left_boundary_edge();

    Vertex_descriptor v = create_vertex(p);

    // Reuse e_left_boundary as the left edge of v.
    topo.set_right_vertex(e_left_boundary, v);
    topo.set_left_edge(v, e_left_boundary);

    if constexpr (is_identified) {
      // Identified parameter space: one vertex, one edge. No new edge is created.
      topo.set_left_vertex(e_left_boundary, v);
      topo.set_right_edge(v, e_left_boundary);
    }
    else {
      // Open / closed parameter space: create the right sub-edge.
      Edge_descriptor e_right = topo.create_edge();
      topo.set_left_vertex(e_right, v);
      topo.set_right_edge(v, e_right);
      topo.set_right_boundary_edge(e_right);
    }

    return v;
  }

  /*! inserts a vertex at the left boundary of a left-closed arrangement.  Sets
   * `p` as the left vertex of left_boundary_edge(); no new edge is created.
   */
  Vertex_descriptor insert_left_boundary_vertex(const Point_1& p) {
    static_assert(left_is_closed,
                  "insert_left_boundary_vertex() is only valid for arrangements with a closed left boundary.");
    auto& topo = m_topology_traits;
    auto e_lb = topo.left_boundary_edge();
    CGAL_precondition(! topo.has_left_vertex(e_lb));
    CGAL_precondition(m_geometry_traits->parameter_space_in_x_1_object()(p) == Parameter_space::LEFT_BOUNDARY);
    Vertex_descriptor v = create_vertex_at(p);
    topo.set_left_boundary_vertex(v);
    topo.set_left_vertex(e_lb, v);
    topo.set_left_edge(v, e_lb);
    topo.set_right_edge(v, e_lb);
    return v;
  }

  /*! inserts a vertex at the right boundary of a right-bounded arrangement.
   * Sets `p` as the right vertex of `e`, the rightmost edge; no new edge is
   * created.
   * \pre `e` is the right boundary edge and has no right vertex.
   */
  Vertex_descriptor insert_right_boundary_vertex(Edge_descriptor e, const Point_1& p) {
    static_assert(right_is_closed,
                  "insert_right_boundary_vertex() is only valid for arrangements with a closed right boundary.");
    auto& topo = m_topology_traits;
    CGAL_precondition(e == topo.right_boundary_edge());
    CGAL_precondition(! topo.has_right_vertex(e));
    CGAL_precondition(m_geometry_traits->parameter_space_in_x_1_object()(p) == Parameter_space::RIGHT_BOUNDARY);
    Vertex_descriptor v = create_vertex_at(p);
    topo.set_right_boundary_vertex(v);
    topo.set_right_vertex(e, v);
    topo.set_left_edge(v, e);
    topo.set_right_edge(v, e);
    return v;
  }

  /*! inserts a vertex at the identification point of an identified
   * arrangement.  Sets `p` as the left vertex of left_boundary_edge();
   * no new edge is created.
   *
   * left_boundary_edge() is the wrap-around arc (its right vertex is v_id).
   * The identification-point vertex v has:
   *   v.left_edge  = left_boundary_edge()   (the arc ending at v from the left)
   *   v.right_edge = first_interior_arc     (the arc leaving v toward the right)
   *
   * In a degenerate arrangement with v_id as the only vertex,
   * first_interior_arc = left_boundary_edge() (a self-loop).
   *
   * If the arrangement was empty when this is called (lb_edge has no right
   * vertex), v is also set as the right vertex of lb_edge (self-loop).
   */
  Vertex_descriptor insert_identification_vertex(const Point_1& p) {
    static_assert(is_identified, "insert_identification_vertex() is only valid for identified arrangements.");
    CGAL_assertion_msg(! m_topology_traits.has_identification_vertex(), "The identification vertex already exists.");
    CGAL_assertion_msg(! empty(), "The arrangement must be non-empty.");
    CGAL_precondition(m_geometry_traits->is_on_x_identification_1_object()(p));
    auto& topo = m_topology_traits;
    auto e_lb = topo.left_boundary_edge();
    Vertex_descriptor v = create_vertex_at(p);
    topo.set_identification_vertex(v);
    Edge_descriptor e_left = create_edge();

    Vertex_descriptor v_old_left = topo.left_vertex(e_lb);
    topo.set_left_vertex(e_left, v_old_left);
    topo.set_right_edge(v_old_left, e_left);
    topo.set_right_vertex(e_left, v);
    topo.set_left_vertex(e_lb, v);
    topo.set_left_edge(v, e_left);
    topo.set_right_edge(v, e_lb);
    topo.set_right_boundary_edge(e_left);

    return v;
  }

  /*! inserts a new point `p` strictly to the left of an existing vertex `v`.
   * \pre `p` lies in the interior of the parameter space.
   */
  Vertex_descriptor insert_before(Vertex_descriptor v, const Point_1& p) {
    if constexpr (binary_search_enabled) {
      CGAL_error_msg("insert_before() cannot be invoked when binary_search_enabled is true. "
                     "Vertices must be appended in strictly increasing x-order.");
    }
    CGAL_precondition(is_interior(p));

    Vertex_descriptor v_new = create_vertex_at(p);
    Edge_descriptor e_between = create_edge();

    Edge_descriptor e_left = m_topology_traits.left_edge(v);

    // Create a new edge to sit between v_new and v: (v_new, v)
    m_topology_traits.set_left_vertex(e_between, v_new);
    m_topology_traits.set_right_vertex(e_between, v);

    // The old left edge now terminates at v_new on its right
    m_topology_traits.set_right_vertex(e_left, v_new);

    // v_new sits between e_left and e_between.
    m_topology_traits.set_left_edge(v_new, e_left);
    m_topology_traits.set_right_edge(v_new, e_between);

    // v's left edge is now e_between.
    m_topology_traits.set_left_edge(v, e_between);

    // Both edges of the right boundary vertex are its left edge.
    if constexpr (right_is_closed) {
      if (m_topology_traits.right_edge(v) == e_left) m_topology_traits.set_right_edge(v, e_between);
    }

    // If v is at the right boundary, e_between is the new right boundary edge.
    if (ends_at_right_boundary(e_left)) m_topology_traits.set_right_boundary_edge(e_between);

    return v_new;
  }

  /*! inserts a new point `p` strictly to the right of an existing vertex `v`.
   * \pre `p` lies in the interior of the parameter space.
   */
  Vertex_descriptor insert_after(Vertex_descriptor v, const Point_1& p) {
    CGAL_precondition(is_interior(p));
    if constexpr (binary_search_enabled) {
      // Enforce that v is the current rightmost vertex
      CGAL_assertion_msg(v == m_topology_traits.number_of_vertices() - 1,
                         "When BinarySearch = true, insert_after() can only be called on the rightmost vertex.");
    }

    // Both edges of the left boundary vertex are left_boundary_edge(), which
    // must remain the leftmost edge; split it instead.
    if constexpr (left_is_closed) {
      if (m_topology_traits.left_edge(v) == m_topology_traits.right_edge(v))
        return split_edge(m_topology_traits.right_edge(v), p);
    }

    // The right edge of the identification vertex is left_boundary_edge(),
    // whose left end must remain at the identification point; split it instead.
    if constexpr (is_identified) {
      if (m_topology_traits.has_identification_vertex() && (v == m_topology_traits.identification_vertex()))
        return split_edge(m_topology_traits.right_edge(v), p);
    }

    Vertex_descriptor v_new = create_vertex_at(p);
    Edge_descriptor e_between = create_edge();

    Edge_descriptor e_right = m_topology_traits.right_edge(v);

    // Create a new edge to sit between v_new and v: (v_new, v)
    m_topology_traits.set_left_vertex(e_between, v);
    m_topology_traits.set_right_vertex(e_between, v_new);

    // The old right edge now starts from v_new
    m_topology_traits.set_left_vertex(e_right, v_new);

    // v_new is wired between e_between and e_right.
    m_topology_traits.set_left_edge(v_new, e_between);
    m_topology_traits.set_right_edge(v_new, e_right);

    // v's right edge is now e_between.
    m_topology_traits.set_right_edge(v, e_between);

    return v_new;
  }

  /*! splits the edge `e` by inserting a new point `p` inside it.
   * `e` becomes the left sub-edge; a new edge becomes the right sub-edge,
   * so that `e` retains its identity (left_boundary_edge() remains stable).
   * If `e` is the right boundary edge, the new edge becomes the right
   * boundary edge, unless the arrangement is identified and the
   * identification vertex does not exist.
   * \pre `p` lies in the interior of the parameter space.
   */
  Vertex_descriptor split_edge(Edge_descriptor e, const Point_1& p) {
    CGAL_precondition(is_interior(p));

    if constexpr (binary_search_enabled) {
      CGAL_assertion_msg(! m_topology_traits.has_right_vertex(e),
                         "When BinarySearch = true, split_edge() can only be called on the rightmost edge.");
      CGAL_assertion_msg(! m_topology_traits.has_left_vertex(e) ||
                         m_topology_traits.left_vertex(e) == m_topology_traits.number_of_vertices() - 1,
                         "When BinarySearch = true, the edge being split must originate from the rightmost vertex.");
    }

    Vertex_descriptor v_new = create_vertex_at(p);
    Edge_descriptor e_right = create_edge();

    // Transfer e's right vertex (if any) to e_right.
    if (m_topology_traits.has_right_vertex(e)) {
      Vertex_descriptor v_old_right = m_topology_traits.right_vertex(e);
      m_topology_traits.set_right_vertex(e_right, v_old_right);
      m_topology_traits.set_left_edge(v_old_right, e_right);
      // Both edges of the right boundary vertex are its left edge.
      if constexpr (right_is_closed) {
        if (m_topology_traits.right_edge(v_old_right) == e) m_topology_traits.set_right_edge(v_old_right, e_right);
      }
    }
    m_topology_traits.set_left_vertex(e_right, v_new);

    // e (left sub-edge) now ends at v_new.
    m_topology_traits.set_right_vertex(e, v_new);

    // Wire v_new between e and e_right.
    m_topology_traits.set_left_edge(v_new, e);
    m_topology_traits.set_right_edge(v_new, e_right);

    if (ends_at_right_boundary(e)) m_topology_traits.set_right_boundary_edge(e_right);

    return v_new;
  }

  /*! removes a vertex from the arrangement.
   *
   * If the two edges incident to `v` are distinct, they are merged into one;
   * left_boundary_edge() is always the one kept.  Otherwise, `v` is a boundary
   * vertex of a closed side, or the only vertex of an identified arrangement,
   * and no edge is removed; `v` is detached from its incident edge.
   */
  void remove(Vertex_descriptor v) {
    auto& topo = m_topology_traits;
    Edge_descriptor e_left = topo.left_edge(v);
    Edge_descriptor e_right = topo.right_edge(v);

    if (e_left == e_right) {
      // A boundary vertex is either the left or the right end of its edge; the
      // only vertex of an identified arrangement is both.  Removing the latter
      // restores the spanning edge.
      if (topo.has_left_vertex(e_left) && (topo.left_vertex(e_left) == v)) topo.clear_left_vertex(e_left);
      if (topo.has_right_vertex(e_left) && (topo.right_vertex(e_left) == v)) topo.clear_right_vertex(e_left);
    }
    else if (e_right == topo.left_boundary_edge()) {
      // Identified only: v is the identification vertex, or, if it does not
      // exist, the last vertex.  left_boundary_edge() absorbs e_left.  The
      // identification vertex does not exist afterwards, so left_boundary_edge()
      // is also the right boundary edge.
      Vertex_descriptor u = topo.left_vertex(e_left);
      topo.set_left_vertex(e_right, u);
      topo.set_right_edge(u, e_right);
      topo.set_right_boundary_edge(e_right);
      destroy_edge(e_left);
    }
    else {
      // e_left absorbs e_right.
      if (topo.has_right_vertex(e_right)) {
        Vertex_descriptor w = topo.right_vertex(e_right);
        topo.set_right_vertex(e_left, w);
        topo.set_left_edge(w, e_left);
        // Both edges of the right boundary vertex are its left edge.
        if (topo.right_edge(w) == e_right) topo.set_right_edge(w, e_left);
      }
      else topo.clear_right_vertex(e_left);
      if (e_right == topo.right_boundary_edge()) topo.set_right_boundary_edge(e_left);
      destroy_edge(e_right);
    }

    destroy_vertex(v);
  }

  // ==================================================================
  // BINARY SEARCH SUPPORT (only available / called when Topology_traits::use_vector = true)
  //
  // locate.h calls binary_search_vertex() when the topology traits has
  // BinarySearch = true (detected via the static constexpr below).
  //
  // The vertex vector is maintained in left-to-right sorted order by
  // Arrangement_on_curve_1's high-level insert operations.  We perform a
  // standard lower_bound-style search using the geometry traits' comparator.
  //
  // Returns:
  //   - the index of the matching vertex if p coincides with one, or
  //   - the index of the first vertex whose x-coordinate is > p, which is
  //     the right endpoint of the edge that contains p.
  //     (An out-of-range index equal to m_vertices.size() means p is to the
  //      right of all vertices, i.e. it lies in the rightmost edge.)
  //
  // The caller distinguishes the two cases by comparing the returned index
  // against m_vertices.size() and, if in range, by checking whether cmp
  // returns EQUAL for the vertex at that index.
  // ==================================================================
  template <typename Compare>
  std::size_t binary_search_vertex(const Point_1& p, Compare cmp) const {
    static_assert(Topology_traits::use_vector, "binary_search_vertex() is only available when use_vector = true.");

    const auto& vertices = m_topology_traits.raw_vertices();

    std::size_t lo = 0, hi = vertices.size();
    while (lo < hi) {
      std::size_t mid = lo + (hi - lo) / 2;
      auto res = cmp(vertices[mid].m_point, p);
      if (res == SMALLER) lo = mid + 1;
      else if (res == LARGER)  hi = mid;
      else return mid; // EQUAL: vertex found
    }
    // p is not at any vertex; lo is the index of the first vertex > p.
    return lo;
  }

private:
  // determines whether `e` is the right boundary edge and its right end is at
  // the right boundary.  In an identified arrangement without the
  // identification vertex, the right boundary edge is left_boundary_edge(),
  // which contains the identification point and remains the right boundary
  // edge when it is split.
  bool ends_at_right_boundary(Edge_descriptor e) const {
    if (e != m_topology_traits.right_boundary_edge()) return false;
    if constexpr (is_identified) return m_topology_traits.has_identification_vertex();
    else return true;
  }
};

